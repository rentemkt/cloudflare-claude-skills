// Sistema de gerenciamento de idiomas
class LanguageManager {
    constructor() {
        this.currentLanguage = this.detectLanguage();
        this.basePath = this.getBasePath();
        this.init();
    }
    
    detectLanguage() {
        // Detecta idioma da URL ou localStorage
        const urlParams = new URLSearchParams(window.location.search);
        const urlLang = urlParams.get('lang');
        const storedLang = localStorage.getItem('espacoConsciencia_language');
        const browserLang = navigator.language.substring(0, 2);
        
        if (urlLang && translations[urlLang]) {
            return urlLang;
        }
        if (storedLang && translations[storedLang]) {
            return storedLang;
        }
        if (translations[browserLang]) {
            return browserLang;
        }
        return 'pt'; // Padrão português
    }
    
    getBasePath() {
        // Detecta o caminho base da aplicação
        const path = window.location.pathname;
        const segments = path.split('/').filter(segment => segment);
        
        if (segments.length > 0) {
            // Se estiver em subpasta, retorna o caminho base
            return '/' + segments[0] + '/';
        }
        return '/';
    }
    
    init() {
        this.translatePage();
        this.setupLanguageSelector();
        this.updateLanguageSelector();
    }
    
    translatePage() {
        const elements = document.querySelectorAll('[data-translate]');
        elements.forEach(element => {
            const key = element.getAttribute('data-translate');
            const translation = this.getTranslation(key);
            if (translation) {
                element.innerHTML = translation;
            }
        });
    }
    
    getTranslation(key) {
        const keys = key.split('.');
        let translation = translations[this.currentLanguage];
        
        for (const k of keys) {
            if (translation && translation[k]) {
                translation = translation[k];
            } else {
                return translations.pt[key] || key; // Fallback para português
            }
        }
        
        return translation;
    }
    
    changeLanguage(newLanguage) {
        if (!translations[newLanguage]) return;
        
        this.currentLanguage = newLanguage;
        localStorage.setItem('espacoConsciencia_language', newLanguage);
        
        // Atualiza URL sem recarregar a página
        const url = new URL(window.location);
        url.searchParams.set('lang', newLanguage);
        window.history.replaceState({}, '', url);
        
        this.translatePage();
        this.updateLanguageSelector();
    }
    
    setupLanguageSelector() {
        const languageButtons = document.querySelectorAll('[data-language]');
        languageButtons.forEach(button => {
            button.addEventListener('click', (e) => {
                e.preventDefault();
                const language = button.getAttribute('data-language');
                this.changeLanguage(language);
            });
        });
    }
    
    updateLanguageSelector() {
        // Atualiza o seletor de idiomas ativo
        const languageButtons = document.querySelectorAll('[data-language]');
        languageButtons.forEach(button => {
            const language = button.getAttribute('data-language');
            if (language === this.currentLanguage) {
                button.classList.add('active');
            } else {
                button.classList.remove('active');
            }
        });
        
        // Atualiza o texto do seletor principal
        const mainSelector = document.querySelector('.language-selector-main');
        if (mainSelector) {
            const flagMap = {
                'pt': '🇵🇹 Português',
                'en': '🇺🇸 English',
                'es': '🇪🇸 Español'
            };
            mainSelector.textContent = flagMap[this.currentLanguage] || '🇵🇹 Português';
        }
    }
    
    getLocalizedUrl(path) {
        // Gera URLs localizadas baseadas no idioma atual
        const translations_urls = translations[this.currentLanguage];
        if (translations_urls && translations_urls[`url.${path}`]) {
            return this.basePath + translations_urls[`url.${path}`];
        }
        return this.basePath + path;
    }
}

// Inicializa o sistema quando o DOM estiver carregado
document.addEventListener('DOMContentLoaded', () => {
    window.languageManager = new LanguageManager();
});

// Exporta para uso global
window.translations = translations;

